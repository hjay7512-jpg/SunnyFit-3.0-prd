const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const {spawn} = require('node:child_process')
const {randomUUID} = require('node:crypto')
const {chromium} = require('playwright-core')
const root = path.resolve(__dirname, '..'), base = 'http://127.0.0.1:3123'
const dir = path.join(root, 'docs', 'ai-ball-validation', new Date().toISOString().replace(/[:.]/g, '-'))
const report = {checks: [], errors: [], startedAt: new Date().toISOString()}
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
const pass = name => {report.checks.push(name); console.log('PASS ' + name)}
let browser, server, page, output = ''

async function open(screen, review = '0') {
  await page.goto(base + '/#/app/' + screen + '?user=DEMO-1003&review=' + review)
  await page.locator('.phone-frame[aria-busy="false"]').waitFor()
}
async function showcase() {
  await page.goto(base + '/#/demo/lab?tab=ai-ball')
  await page.locator('.ai-ball-stage').waitFor()
}
async function run() {
  fs.mkdirSync(dir, {recursive: true})
  server = spawn(process.execPath, ['server/index.cjs'], {cwd: root, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'], env: {...process.env, API_PORT: '3123', DEMO_DB_PATH: path.join(root, 'runtime', 'ai-ball-check-' + randomUUID() + '.sqlite')}})
  server.stdout.on('data', chunk => {output += chunk}); server.stderr.on('data', chunk => {output += chunk})
  for (let i = 0; i < 80; i++) {if (server.exitCode !== null) throw Error(output); if (output.includes(base)) break; await pause(100)}
  browser = await chromium.launch({channel: 'msedge', headless: true})
  page = await browser.newPage({viewport: {width: 390, height: 844}, reducedMotion: 'no-preference'})
  page.setDefaultTimeout(10000); page.on('pageerror', error => report.errors.push(error.message))
  await open('home')
  const entry = page.getByRole('button', {name: 'Open AI Coach', exact: true})
  const ball = entry.locator('.sf-ai-ball')
  await ball.waitFor(); const bounds = await entry.boundingBox()
  assert.ok(await ball.evaluate(element=>{const eyes=[...element.querySelectorAll('.sf-ai-ball__eye')].map(e=>e.transform.baseVal.consolidate().matrix);return eyes.length===2&&eyes[0].e===24&&eyes[1].e===32&&eyes.every(e=>e.f===30.5&&e.a===1&&e.d===1&&e.b===0&&e.c===0)}),'Resting eyes must match the original neutral pose')
  pass('default eyes are level, upright and centred on the face')
  await page.waitForFunction(() => !document.querySelector('[data-action="coach"] .sf-ai-ball').classList.contains('sf-ai-ball--paused'))
  const before = await entry.screenshot({path: path.join(dir, 'home-frame-a.png')})
  // Sample the running browser timeline, rather than assuming a CSS name means visible movement.
  const timelinePromise = ball.evaluate(element => new Promise(resolve => {
    const values = [], start = performance.now()
    function sample() {
      const matrix = selector => new DOMMatrixReadOnly(getComputedStyle(element.querySelector(selector)).transform)
      const eyes = matrix('.sf-ai-ball__lid'), colour = matrix('[data-face-track="colours"]')
      const anchors=[...element.querySelectorAll('.sf-ai-ball__eye')].map(e=>e.transform.baseVal.consolidate().matrix)
      values.push({at:performance.now()-start,eyeHeight:eyes.m22,eyeX:(anchors[0].e+anchors[1].e)/2,eyeY:(anchors[0].f+anchors[1].f)/2,colourX:colour.m41,colourY:colour.m42,yaw:Number(element.dataset.headYaw),pitch:Number(element.dataset.headPitch)})
      if (performance.now() - start < 12200) requestAnimationFrame(sample); else resolve(values)
    }
    requestAnimationFrame(sample)
  }))
  await page.waitForFunction(()=>Number(document.querySelector('[data-action="coach"] .sf-ai-ball').dataset.headYaw)<-.99)
  const after = await entry.screenshot({path: path.join(dir, 'home-frame-b.png')})
  const timeline = await timelinePromise
  report.homeTimeline = timeline
  assert.ok(Math.min(...timeline.map(v => v.eyeHeight)) < .12, 'Home must visibly close its eyes in the first seconds')
  assert.ok(Math.max(...timeline.map(v => v.eyeX)) - Math.min(...timeline.map(v => v.eyeX)) > 2, 'Home gaze must move visibly')
  assert.ok(Math.max(...timeline.map(v => v.colourX)) - Math.min(...timeline.map(v => v.colourX)) > 1, 'Internal colour groups must move')
  assert.ok(timeline.every(v=>Math.abs(v.colourX-v.yaw*(v.yaw<0?2:3))<.001&&Math.abs(v.colourY+6*v.pitch)<.001),'Colour and eye projections must share one head pose')
  assert.ok(timeline.filter(v=>Math.abs(v.yaw)<.05).length>timeline.length*.5,'Standby must spend most of its time facing forward')
  assert.ok(timeline.filter(v=>v.yaw<-.95).every(v=>v.eyeX<24&&v.eyeY<26&&v.colourY<-5.5),'Side view must look upward with both face layers')
  const moving=timeline.filter(v=>v.yaw<-.01&&v.yaw>-.99)
  assert.ok(moving.length>80,'A head turn must render many intermediate frames')
  assert.deepEqual(await entry.boundingBox(), bounds)
  pass('Home blinks early, then turns slowly while spending most of its time facing forward')
  pass('one head pose projects the face and eyes upward into a side view across continuous frames')
  // Compare the original resting frame with the natural slow head turn sampled above.
  assert.ok(!before.equals(after), 'Rendered frames must differ')
  await page.locator('.phone-frame').screenshot({path: path.join(dir, 'home-390.png')})
  pass('actual Home renders different frames, rather than a static image')
  assert.ok(await ball.evaluate(element => {
    const clip = element.querySelector('clipPath circle'), body = element.querySelector('.sf-ai-ball__body')
    const glass = element.querySelector('[data-layer="glass-cover"]'), eyes = element.querySelector('[data-layer="eyes-outside-glass"]')
    return Number(clip.getAttribute('r')) < Number(body.getAttribute('r')) && Boolean(glass.compareDocumentPosition(eyes) & Node.DOCUMENT_POSITION_FOLLOWING) && !eyes.closest('[filter]')
  }))
  pass('colour groups have an inset boundary, with glass above them and unblurred eyes outside the glass')
  await entry.hover(); await page.waitForFunction(() => document.querySelector('[data-action="coach"] .sf-ai-ball').classList.contains('sf-ai-ball--blink'))
  await page.waitForFunction(() => !document.querySelector('[data-action="coach"] .sf-ai-ball').classList.contains('sf-ai-ball--blink'))
  await entry.focus(); await page.keyboard.press('Enter'); await page.getByLabel('Message AI', {exact: true}).waitFor()
  assert.ok(page.url().includes('/app/coach'))
  pass('hover gives immediate eye feedback and the existing Home entry remains keyboard operable')

  const coachBall = page.locator('.visual-coach .sf-ai-ball')
  await page.getByLabel('Message AI', {exact: true}).fill('What should I focus on today?')
  assert.equal(await coachBall.getAttribute('data-state'), 'listening')
  let release; const held = new Promise(resolve => {release = resolve})
  await page.route('**/api/commercialization/service-start', async route => {await held; await route.continue()})
  await page.locator('[data-action="send"]').click()
  await page.locator('.visual-coach .sf-ai-ball[data-state="thinking"]').waitFor()
  await page.locator('.phone-frame').screenshot({path: path.join(dir, 'coach-thinking.png')})
  release(); await page.locator('.assistant-bubble').waitFor(); await page.unroute('**/api/commercialization/service-start')
  assert.equal(await coachBall.getAttribute('data-state'), 'success')
  pass('Coach transitions from input to thinking to success using the real Demo request lifecycle')
  await open('coach', '1'); await page.getByRole('checkbox', {name: '模拟 LLM 失败并释放额度'}).check()
  await page.getByLabel('Message AI', {exact: true}).fill('Keep this input after a failure')
  await page.locator('[data-action="send"]').click(); await page.getByRole('heading', {name: 'Let’s try again', exact: true}).waitFor()
  assert.equal(await coachBall.getAttribute('data-state'), 'error')
  assert.equal(await page.getByLabel('Message AI', {exact: true}).inputValue(), 'Keep this input after a failure')
  pass('failure drives the error face and preserves the actual message')

  await page.setViewportSize({width: 1280, height: 1000}); await showcase()
  const stageBall = page.locator('.ai-ball-stage .sf-ai-ball'), picker = page.getByRole('tablist', {name: 'AI activity'})
  const states = [['待命','idle'],['收集信息','listening'],['思考生成','thinking'],['输出内容','responding'],['完成','success'],['失败','error']]
  for (const [label, state] of states) {
    await picker.getByRole('tab', {name: label, exact: true}).click(); assert.equal(await stageBall.getAttribute('data-state'), state)
  }
  assert.ok(await page.locator('.sf-ai-ball').evaluateAll(elements => {const ids = elements.flatMap(e => [...e.querySelectorAll('[id]')].map(x => x.id)); return ids.length === new Set(ids).size}))
  pass('all six public states switch without SVG resource collisions')
  await picker.getByRole('tab', {name:'待命',exact:true}).click()
  for(const [direction,expected] of [['left',[[18.891,23.818],[26.717,25.481]]],['right',[[30.029,25.617],[37.792,23.681]]]]) {
    await page.getByLabel('视线',{exact:true}).selectOption(direction)
    await page.waitForFunction(side=>Math.abs(Number(document.querySelector('.ai-ball-stage .sf-ai-ball').dataset.headYaw)-(side==='left'?-1:1))<.001,direction)
    const anchors=await stageBall.locator('.sf-ai-ball__eye').evaluateAll(elements=>elements.map(e=>{const m=e.transform.baseVal.consolidate().matrix;return [m.e,m.f]}))
    anchors.forEach((point,index)=>point.forEach((v,axis)=>assert.ok(Math.abs(v-expected[index][axis])<.02)))
    await page.locator('.ai-ball-stage').screenshot({path:path.join(dir,'pose-'+direction+'.png'),animations:'disabled'})
  }
  await page.getByLabel('视线',{exact:true}).selectOption('center')
  await page.waitForFunction(()=>Math.abs(Number(document.querySelector('.ai-ball-stage .sf-ai-ball').dataset.headYaw))<.001)
  await page.locator('.ai-ball-stage').screenshot({path:path.join(dir,'pose-center.png'),animations:'disabled'})
  await page.getByLabel('视线',{exact:true}).selectOption('auto')
  pass('neutral and left-up/right-up eye anchors match the original Figma poses')
  await picker.getByRole('tab', {name: '待命', exact: true}).click()
  await page.getByRole('button', {name: 'Preview blink', exact: true}).click()
  assert.equal(await stageBall.getAttribute('data-state'), 'idle')
  await page.waitForFunction(() => !document.querySelector('.ai-ball-stage .sf-ai-ball').classList.contains('sf-ai-ball--blink'))
  pass('manual blink is transient and does not change business state')
  await page.getByRole('switch', {name: '减少 AI 动态效果'}).click()
  assert.ok(await stageBall.evaluate(element => [...element.querySelectorAll('*')].every(e => getComputedStyle(e).animationName === 'none')))
  await page.getByRole('button', {name: 'Preview blink', exact: true}).click()
  assert.ok(!(await stageBall.getAttribute('class')).includes('sf-ai-ball--blink'))
  await page.getByRole('switch', {name: '减少 AI 动态效果'}).click(); await page.emulateMedia({reducedMotion: 'reduce'})
  assert.ok(await stageBall.evaluate(element => [...element.querySelectorAll('*')].every(e => getComputedStyle(e).animationName === 'none')))
  await page.emulateMedia({reducedMotion: 'no-preference'})
  pass('explicit and system reduced-motion preferences stop eye and colour animation')

  // Reproduce the actual user's Chrome failure: system motion is reduced, then the Demo explicitly opts in.
  await page.emulateMedia({reducedMotion: 'reduce'})
  await page.getByRole('switch', {name: '完整动效预览', exact: true}).click()
  assert.equal(await stageBall.getAttribute('data-motion'), 'full')
  assert.notEqual(await stageBall.locator('.sf-ai-ball__lid').first().evaluate(e => getComputedStyle(e).animationName), 'none')
  await page.reload(); await page.locator('.ai-ball-stage').waitFor()
  assert.equal(await stageBall.getAttribute('data-motion'), 'full')
  await page.getByRole('switch', {name: '减少 AI 动态效果'}).click()
  assert.equal(await stageBall.locator('.sf-ai-ball__lid').first().evaluate(e => getComputedStyle(e).animationName), 'none')
  await page.getByRole('switch', {name: '减少 AI 动态效果'}).click()
  await page.getByRole('switch', {name: '完整动效预览', exact: true}).click()
  assert.equal(await stageBall.locator('.sf-ai-ball__lid').first().evaluate(e => getComputedStyle(e).animationName), 'none')
  await page.emulateMedia({reducedMotion: 'no-preference'})
  pass('Demo opt-in plays despite system reduction, survives reload, and can return to reduced motion')

  const scene = page.locator('.ai-scene').first()
  await scene.getByLabel('Feel stronger', {exact: true}).check(); await scene.getByRole('button', {name: 'Continue', exact: true}).click()
  await scene.getByLabel('10–15 minutes', {exact: true}).check(); await scene.getByRole('button', {name: 'Continue', exact: true}).click()
  await scene.getByLabel('Some experience', {exact: true}).check(); await scene.getByRole('button', {name: 'Finish questionnaire', exact: true}).click()
  await scene.getByRole('button', {name: 'Cancel generation', exact: true}).click()
  assert.ok(await scene.getByLabel('Some experience', {exact: true}).isChecked()); await pause(1900)
  assert.equal(await scene.locator('.sf-ai-ball').getAttribute('data-state'), 'listening')
  pass('cancelled questionnaire generation retains answers and cancels its stale completion')
  await scene.getByRole('switch', {name: '模拟生成失败'}).click(); await scene.getByRole('button', {name: 'Finish questionnaire', exact: true}).click()
  await scene.getByRole('button', {name: 'Retry', exact: true}).waitFor(); assert.equal(await scene.locator('.sf-ai-ball').getAttribute('data-state'), 'error')
  await scene.getByRole('switch', {name: '模拟生成失败'}).click(); await scene.getByRole('button', {name: 'Retry', exact: true}).click()
  await scene.getByRole('button', {name: 'Start again', exact: true}).waitFor()
  assert.match(await scene.innerText(), /Feel stronger · 10–15 minutes · Some experience/)
  pass('questionnaire failure and retry preserve the collected information')
  await scene.getByRole('button', {name: 'Start again', exact: true}).click()
  await page.locator('.ai-ball-showcase').screenshot({path: path.join(dir, 'showcase.png')})
  for (const width of [375,390,430]) {
    await page.setViewportSize({width,height:900}); await open('home')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    const target = await page.getByRole('button', {name: 'Open AI Coach', exact: true}).boundingBox()
    assert.ok(target.width >= 44 && target.height >= 44)
    pass(width + ' px Home keeps the existing AI target visible and contained')
  }
  assert.deepEqual(report.errors, []); report.status = 'passed'
}
run().catch(async error => {report.status = 'failed'; report.failure = error.stack; console.error(error.stack); process.exitCode = 1; if(page)await page.screenshot({path:path.join(dir,'failure.png')}).catch(()=>{})}).finally(async () => {fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(path.join(dir,'results.json'),JSON.stringify(report,null,2));if(browser)await browser.close();if(server)server.kill();console.log('Evidence: '+dir)})
