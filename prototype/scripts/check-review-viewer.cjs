const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { chromium } = require('playwright-core')
const { server } = require('./review-viewer.cjs')
let browser
async function run() {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const base = 'http://127.0.0.1:' + server.address().port
  assert.equal((await fetch(base + '/package.json')).status, 403)
  assert.equal((await fetch(base + '/docs/%2e%2e%2fpackage.json')).status, 403)
  assert.equal((await fetch(base + '/docs/missing.md')).status, 404)
  assert.equal((await fetch(base + '/', { method: 'POST' })).status, 405)
  const foreignHostStatus = await new Promise((resolve, reject) => {
    const request = http.get(base + '/', { headers: { Host: 'example.com' } }, response => { response.resume(); resolve(response.statusCode) })
    request.on('error', reject)
  })
  assert.equal(foreignHostStatus, 403)
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base + '/latest')
  assert.match(await page.locator('h1').innerText(), /三轮验证结果与更新方案/)
  assert.ok(await page.locator('table').count() >= 5)
  assert.equal(await page.locator('a').filter({ hasText: '查看源文件' }).count(), 1)
  const preview = path.resolve(__dirname, '../runtime/review-viewer-preview.png')
  fs.mkdirSync(path.dirname(preview), { recursive: true })
  await page.screenshot({ path: preview })
  await page.getByRole('link', { name: '已解锁仍显示价格', exact: true }).click()
  await page.waitForFunction(() => document.images.length === 1 && document.images[0].complete && document.images[0].naturalWidth > 0)
  await page.goto(base + '/')
  await page.getByRole('textbox', { name: '搜索文件名' }).fill('Validation_And_Update')
  await page.getByRole('button', { name: '查找', exact: true }).click()
  assert.equal(await page.locator('.doc-list li').count(), 1)
  await page.locator('.doc-list a').click()
  await page.getByRole('link', { name: '查看源文件', exact: true }).click()
  assert.match(await page.locator('body').innerText(), /# SunnyFit V3 Demo/)
  assert.deepEqual(errors, [])
  console.log('PASS: formatted document, tables, screenshot links, search, raw source, read-only methods and file boundaries.')
  console.log('Preview: runtime/review-viewer-preview.png')
}
run().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => {
  if (browser) await browser.close()
  if (server.listening) await new Promise(resolve => server.close(resolve))
})
