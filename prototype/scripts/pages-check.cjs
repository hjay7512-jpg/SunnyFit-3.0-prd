    await page.locator('[data-review-component=camera] [data-state=demo]').click();await page.getByRole('button',{name:'Start vision recognition',exact:true}).click()
    await page.locator('[data-review-component=framing] [data-state=in-view]').click();await page.locator('.movement-experience--training').waitFor({timeout:10000})
    const movementMedia=await page.evaluate(()=>{const vm=document.querySelector('.movement-experience').__vue__;return{current:vm.media(vm.current),custom:vm.media({videoUrl:'/assets/movement/media/curl.mp4'})}})
    assert.ok(movementMedia.current.startsWith(base));assert.ok(movementMedia.custom.startsWith(base))
