    assert.ok(movement&&movement.training.vision.supported)
    await visit('/app/movement?user=DEMO-2002&review=1&membershipState=active')
    await page.locator('[data-content-id="'+movement.id+'"]').getByRole('button',{name:'View workout'}).click()
